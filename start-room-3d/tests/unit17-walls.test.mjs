import assert from 'node:assert/strict';
import {MAP,SPRITES,CHAR_SPRITES,PARTITION,defaultPlacement,restorePlacement,footprintCells,validPlacement,rotateDir,characterDepthEntries} from '../map-data.js';
import {preservesEntrance,pathfind,tickManager} from '../navigation.js';
import {newState,newWorld} from '../sim.js';
const zone=MAP.zones[0],base=defaultPlacement().slots;
const wall=(id,origin)=>({id,type:'wall',origin,dir:0});
assert.equal(SPRITES.wall.file,null);assert.ok(CHAR_SPRITES.manager.file.endsWith('manager-stand-dr.png'));assert.deepEqual(CHAR_SPRITES.manager.anchor,[64,166]);
assert.deepEqual(PARTITION,{count:3,price:50000});
const w=wall('wall-a',[2,2]);assert.deepEqual(footprintCells(w),[[2,2]]);
assert.equal(validPlacement(w,base,zone),true);
assert.equal(preservesEntrance(zone,base,[...base,w]),true);
assert.equal(validPlacement(wall('wall-b',zone.entrance),base,zone),false);
assert.equal(preservesEntrance(zone,base,[...base,wall('wall-b',zone.entrance)]),false);
const barrier=Array.from({length:zone.cols},(_,i)=>wall('cut-'+i,[i,4]));
assert.equal(preservesEntrance(zone,base,[...base,...barrier]),false);
assert.equal(pathfind(zone,[...base,w],[0,5],[2,2]),null);
assert.ok(pathfind(zone,[...base,w],[0,5],[5,5]));
const saved={v:1,slots:[...base,w]};assert.deepEqual(restorePlacement(saved),saved);
const rotated={...w,dir:rotateDir('wall',w.dir)};
assert.equal(preservesEntrance(zone,saved.slots,[...base,rotated]),true);
assert.deepEqual(footprintCells(rotated),footprintCells(w));
// Rotation of a two-cell counter can seal the entrance even though its footprint is in bounds.
const corridor={...zone,cols:3,rows:3,entrance:[0,2]};
const before=[{id:'counter',type:'counter',origin:[1,0],dir:1}];
const after=[{...before[0],origin:[0,1],dir:0},wall('seal',[2,1])];
assert.equal(preservesEntrance(corridor,before,after),false);
assert.equal(preservesEntrance(zone,saved.slots,base),true);
const s=newState(0);s.placement=saved;const world=newWorld(s,()=>.9);
tickManager(s,world,0,true,1);const start=[...world.manager.cell];
for(let i=0;i<20;i++)tickManager(s,world,1,true,1);
assert.deepEqual(world.manager.cell,start);world.custs=[{phase:'seated',cell:[1,3]}];tickManager(s,world,0,true,1);assert.equal(world.manager.phase,'walking');for(let i=0;i<zone.cols*zone.rows&&world.manager.phase==='walking';i++)tickManager(s,world,1,true,1);assert.equal(world.manager.phase,'visiting');
assert.ok(!saved.slots.some(x=>footprintCells(x).some(c=>c.join()===world.manager.cell.join())));
assert.equal(characterDepthEntries(world).filter(x=>x.character.role==='manager').length,1);
assert.ok(!world.daycare&&!world.walk&&!world.trainer);
tickManager(s,world,0,false,1);assert.equal(world.manager,null);
console.log('§17 walls: footprint, routes, blocked entrance/cut, rotation, remove, save; manager service navigation passed');
